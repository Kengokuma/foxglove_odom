const assert = require('node:assert/strict');
const ts = require('typescript');
const fs = require('node:fs');
const compiled = ts.transpileModule(fs.readFileSync('src/odom.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } });
const mod = { exports: {} };
new Function('exports', 'module', compiled.outputText)(mod.exports, mod);
const { readPose, Trajectory } = mod.exports;
const msg = (q) => ({ header: { frame_id: 'odom' }, pose: { pose: { position: { x: 1, y: 2, z: 3 }, orientation: q } } });
assert.equal(readPose(undefined), undefined);
assert.equal(readPose(msg({x: 0,y: 0,z: 0,w: 0})), undefined);
assert.equal(readPose(msg({x: NaN,y: 0,z: 0,w: 1})), undefined);
const pose = readPose(msg({x: 0,y: 0,z: 2,w: 2}));
assert.ok(Math.abs(pose.yaw - Math.PI / 2) < 1e-10);
assert.equal(pose.frame, 'odom');
const track = new Trajectory();
track.add(pose); track.add({...pose, x: 1.001});
assert.equal(track.points.length, 1); assert.equal(track.current.x, 1.001);
for(let i=0;i<10010;i++) track.add({...pose, x:i});
assert.equal(track.points.length, 10000);
track.add({...pose, frame:'map'}); assert.equal(track.points.length, 1);
track.clear(); assert.equal(track.points.length, 0); assert.equal(track.current, undefined);
console.log('Odometry parsing, yaw normalization, history bounds, frame changes and reset passed.');
